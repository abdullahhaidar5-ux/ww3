// Bundles the game's battle code into the Worker: writes gen/battle-sim.js, an ES module whose createBattleSim() returns
// one independent battle (its own G, NET...). Source: the game's own files in ../src (01-data, 02-map, 03-sim,
// 07a-hostsnap, 07b-ckpt), joined exactly as orch/headless.mjs does for Node (simSource), plus the server's control
// panel (src/battle-driver.js). The browser game's build (orch/build.py) is not involved and does not change.
//
// Runs automatically before `wrangler dev` / `wrangler deploy` ([build] in wrangler.toml), and from the Node tests.
//   node build-sim.mjs            # write gen/battle-sim.js (only if it changed)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { simSource } from '../orch/headless.mjs';
import { BATTLE_DRIVER } from './src/battle-driver.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const SIM_OUT = path.join(HERE, 'gen', 'battle-sim.js');

export function buildSim() {
  const src = simSource(path.join(HERE, '..', 'src'), { host: true });
  if (/<\/script/i.test(src)) throw new Error('src contains </script');
  const out = `// GENERATED by server/build-sim.mjs from src/01-data.js, 02-map.js, 03-sim.js, 07a-hostsnap.js, 07b-ckpt.js
// and server/src/battle-driver.js. Do not edit: change the game's src/ files (or the driver) instead.
/* eslint-disable */
export function createBattleSim() {
  // the few browser names the battle code touches at load time (same stand-ins as orch/headless.mjs; no window at all)
  const noop = () => {};
  const ctx2d = new Proxy({}, { get: (t, k) => (k in t ? t[k] : noop), set: () => true });
  const canvas = () => ({ width: 0, height: 0, style: {}, getContext: () => ctx2d });
  const store = new Map();
  const document = { createElement: canvas, getElementById: () => null, hidden: true, addEventListener: noop };
  const localStorage = { getItem: k => (store.has(k) ? store.get(k) : null), setItem: (k, v) => store.set(k, String(v)), removeItem: k => store.delete(k) };
  const matchMedia = () => ({ matches: false, addEventListener: noop });
  const navigator = { userAgent: 'ww3-server', hardwareConcurrency: 1 };
  const window = undefined, self = undefined;
  const performance = globalThis.performance;
  return (function () {
${src}
/* ===== server control panel (server/src/battle-driver.js) ===== */
return (${BATTLE_DRIVER.toString()})();
  })();
}
`;
  fs.mkdirSync(path.dirname(SIM_OUT), { recursive: true });
  const old = fs.existsSync(SIM_OUT) ? fs.readFileSync(SIM_OUT, 'utf8') : null;
  if (old !== out) fs.writeFileSync(SIM_OUT, out);
  return { file: SIM_OUT, bytes: out.length, changed: old !== out };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = buildSim();
  console.log(`battle sim ${r.changed ? 'written' : 'up to date'}: ${path.relative(process.cwd(), r.file)} (${(r.bytes / 1024).toFixed(0)} KB)`);
}
