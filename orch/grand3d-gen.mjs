// Generates src/13d-grandterrain.js: real coastlines + rivers for the 3D grand map (Abdullah 2026-11-06 08:04).
// Source: Natural Earth 1:50m land / lakes / rivers (public domain, naturalearthdata.com, via github.com/nvkelso/natural-earth-vector),
// warped with the SAME lon/lat -> map projection as orch/grandmap-gen.mjs, rasterised to a 1200x600 land mask (RLE + base64).
//   node orch/grand3d-gen.mjs [dir-with-ne_50m_land.json,ne_50m_lakes.json,ne_50m_rivers_lake_centerlines.json]
import fs from 'node:fs';
const dir = process.argv[2] || '/tmp/claude-0/ne';
const W = 1200, H = 600, S = 0.5;   // raster = half map size
const LX = [[-180,10],[-130,40],[-60,400],[-12,470],[70,1450],[90,1650],[120,1900],[145,2200],[180,2370]];
const LY = [[75,40],[50,250],[10,700],[-10,820],[-45,1130],[-60,1180]];
const pw = (k, v) => { for (let i = 1; i < k.length; i++) { const a = k[i-1], b = k[i]; const lo = Math.min(a[0], b[0]), hi = Math.max(a[0], b[0]); if (v >= lo && v <= hi) return a[1] + (b[1]-a[1]) * (v-a[0]) / (b[0]-a[0]); } return v < k[0][0] ? k[0][1] : k[k.length-1][1]; };
const gx = lon => pw(LX, Math.max(-180, Math.min(180, lon))), gy = lat => pw(LY, Math.max(-60, Math.min(75, lat)));   // clamped: outside the map's lat/lon range pw() would wrap to the far edge
const load = n => JSON.parse(fs.readFileSync(`${dir}/${n}.json`, 'utf8')).features;
const rings = f => { const g = f.geometry; if (!g) return []; if (g.type === 'Polygon') return g.coordinates; if (g.type === 'MultiPolygon') return g.coordinates.flat(); return []; };
function fill(rs) {   // even-odd scanline fill -> Uint8Array(W*H)
  const out = new Uint8Array(W * H), rows = Array.from({ length: H }, () => []);
  for (const r of rs) for (let i = 0; i < r.length - 1; i++) {
    let x0 = gx(r[i][0]) * S, y0 = gy(r[i][1]) * S, x1 = gx(r[i+1][0]) * S, y1 = gy(r[i+1][1]) * S;
    if (y0 === y1) continue; if (y0 > y1) { [x0, x1] = [x1, x0]; [y0, y1] = [y1, y0]; }
    for (let y = Math.max(0, Math.ceil(y0 - .5)); y < Math.min(H, Math.ceil(y1 - .5)); y++) rows[y].push(x0 + (x1 - x0) * ((y + .5 - y0) / (y1 - y0)));
  }
  rows.forEach((xs, y) => { xs.sort((a, b) => a - b); for (let i = 0; i + 1 < xs.length; i += 2) for (let x = Math.max(0, Math.ceil(xs[i] - .5)); x <= Math.min(W - 1, Math.floor(xs[i+1] - .5)); x++) out[y * W + x] = 1; });
  return out;
}
const land = fill(load('ne_50m_land').flatMap(rings));
const lk = load('ne_50m_lakes').filter(f => (f.properties.scalerank ?? 9) <= 1 || (f.properties.name || '') === 'Caspian Sea');
const lakes = fill(lk.flatMap(rings));
for (let i = 0; i < land.length; i++) if (lakes[i]) land[i] = 0;
// RLE: alternating run lengths starting with sea, varint, per whole raster
const bytes = []; let cur = 0, run = 0;
const put = n => { while (n >= 128) { bytes.push((n & 127) | 128); n >>= 7; } bytes.push(n); };
for (let i = 0; i < land.length; i++) { if (land[i] === cur) run++; else { put(run); cur = land[i]; run = 1; } } put(run);
// rivers: only the long ones, simplified to ~3 px steps, game units
const riv = [];
for (const f of load('ne_50m_rivers_lake_centerlines')) {
  const g = f.geometry; if (!g || (f.properties.scalerank ?? 9) > 6) continue;
  const lines = g.type === 'LineString' ? [g.coordinates] : g.type === 'MultiLineString' ? g.coordinates : [];
  for (const l of lines) { const a = []; let px = -9, py = -9; for (const [lo, la] of l) { const x = Math.round(gx(lo)), y = Math.round(gy(la)); if (Math.hypot(x - px, y - py) < 5) continue; a.push(x, y); px = x; py = y; } if (a.length >= 8) riv.push(a); }
}
const b64 = Buffer.from(bytes).toString('base64');
const js = `// Generated by orch/grand3d-gen.mjs - do not edit by hand. Coastlines/lakes/rivers: Natural Earth (public domain), warped to the grand-map projection.\nconst GT_W=${W},GT_H=${H};\nconst GT_MASK='${b64}';   // RLE (varint runs, sea first) of the ${W}x${H} land mask\nconst GT_RIV=${JSON.stringify(riv)};   // river polylines in map units [x,y,x,y,...]\n`;
fs.writeFileSync(new URL('../src/13d-grandterrain.js', import.meta.url), js);
console.log('land px', land.reduce((a, b) => a + b, 0), 'mask b64', b64.length, 'rivers', riv.length, 'js bytes', js.length);
