// Writes orch/SIGNATURES.md from the GE_SIG block in src/13g-grandeco.js (single source of truth).  node orch/signatures-gen.mjs
import fs from 'node:fs';
const src = fs.readFileSync(new URL('../src/13g-grandeco.js', import.meta.url), 'utf8');
const sig = new Function(src.split('/*SIG-BEGIN*/')[1].split('/*SIG-END*/')[0] + '; return {GE_SIG};')().GE_SIG;
const fxs = new Function(src.match(/const GE_FX=\{[^]*?\};/)[0] + '; return GE_FX;')();
const map = fs.readFileSync(new URL('../src/13-grandmap.js', import.meta.url), 'utf8');
const nats = new Function(map.match(/const GM_NATS=\[[^]*?\n?\];/)[0] + '; return GM_NATS;')();
const name = Object.fromEntries(nats.map(r => [r[0], r[1]]));
const stage = { E: 'grand2 (built)', F: 'grand2 (building, built)', M: 'grand3', L: 'grand6' };
let o = `# Grand-map signature assets — one unique thing per nation (Abdullah 2026-11-05 21:02 "I don't like all countries having the same thing")

Generated by \`node orch/signatures-gen.mjs\` from the \`GE_SIG\` table in \`src/13g-grandeco.js\` — edit the table, not this file.
New-nation helpers add their nation's row to that table (and rerun the generator).

**Rules.** No nation copies another's special. Fixed by Abdullah: Ayatollah = IR, RS, DW · Dear Leader = KP · Mountain Fortress = IR, RS, AF, KD, DW, KP
(a province building, pre-built in the defender's battle) · Bunker Buster = US, IL, RU, CN. Every other nation has its own asset(s).

**Kinds / who builds them.** E = economy asset (grand2: two empire-economy modifiers, listed below) · F = Mountain Fortress (grand2) ·
M = military/strike asset (grand3) · L = leader/political asset (grand6).

**Keeping strength even.** Every economy modifier is worth about the same (≈ 3–5% of an empire's net income or a matching saving), and an E nation
gets exactly two of them, each pair used by one nation only. Nations whose assets are M / L / F get the **interim stipend**
(${['tax', 'upkeep'].map(k => fxs[k]).join(' + ')}) — about the same value — until their military/leader asset ships; grand3/grand6 remove the stipend
when they land and tune the asset to the same value (\`grandtest\` prints income and upkeep per empire so drift shows).

## Economy modifiers
| key | effect |
|---|---|
${Object.entries(fxs).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

## Table
| Code | Nation | Signature asset(s) | Kind | Effect | Built by |
|---|---|---|---|---|---|
`;
for (const c of Object.keys(sig).sort()) for (const [i, s] of sig[c].entries()) {
  const eff = s[0] === 'E' ? `${s[2]} (${s[3].map(k => fxs[k]).join('; ')})` : s[2];
  o += `| ${i ? '' : c} | ${i ? '' : name[c] || c} | ${s[1]} | ${s[0]} | ${eff} | ${stage[s[0]]} |\n`;
}
o += `\n${Object.keys(sig).length} nations listed. The EU retires as a nation once FR, DE and PL are live (its row is not needed). Nations not listed here are playable minor nations (no signature).\n`;
fs.writeFileSync(new URL('./SIGNATURES.md', import.meta.url), o);
console.log('wrote orch/SIGNATURES.md', Object.keys(sig).length, 'nations');
